import type { AgentTool } from '@earendil-works/pi-agent-core'
import { StringEnum } from '@earendil-works/pi-ai'
import { Type } from 'typebox'
import type { TSchema } from 'typebox'
import type { TtsResponseFormat } from './contracts/settings.js'
import { getTtsModelResponseFormats, isTelegramVoiceFormat, loadTtsSettings, stripMarkdownForSpeech, synthesizeTts } from './tts.js'
import type { TtsSettings } from './tts.js'
import type { Database } from './database.js'
import { saveUpload } from './uploads.js'
import type { UploadDescriptor } from './uploads.js'

export const SEND_VOICE_MESSAGE_TOOL_NAME = 'audio_send'

/** Keeps a reply a voice message rather than an audiobook, and below most providers' input limits. */
const MAX_SPEECH_CHARS = 4000

export interface SendVoiceMessageToolOptions {
  /** User the upload is attributed to; undefined for callers without a user row. */
  getCurrentUserId: () => number | undefined
  getCurrentInteractiveSessionId: () => string | null | undefined
  /** Channel of the current turn (`telegram`, `web`, …). */
  getChannel: () => string | undefined
  /** Settings the declaration is built from; defaults to the saved settings. */
  settings?: TtsSettings
  /** Books the synthesized characters in the token usage; omitted in tests. */
  db?: Database
}

export interface SendVoiceMessageToolDetails {
  uploadedFile?: UploadDescriptor
  format?: TtsResponseFormat
  error?: boolean
}

export function isSendVoiceMessageToolEnabled(settings: TtsSettings): boolean {
  return settings.enabled && settings.agentTool && settings.model !== ''
}

/** `audio_send` when TTS is enabled and offered to the agent in the settings, otherwise nothing. */
export function createSendVoiceMessageTools(options: Omit<SendVoiceMessageToolOptions, 'settings'>): AgentTool[] {
  let settings: TtsSettings
  try {
    settings = loadTtsSettings()
  } catch {
    return []
  }
  return isSendVoiceMessageToolEnabled(settings) ? [createSendVoiceMessageTool({ ...options, settings })] : []
}

/** Telegram shows OGG/Opus (smallest) and MP3 as a native voice message, so those win there. */
function defaultFormat(formats: readonly TtsResponseFormat[], settings: TtsSettings, channel: string | undefined): TtsResponseFormat {
  if (channel === 'telegram') {
    if (formats.includes('opus')) return 'opus'
    if (formats.includes('mp3')) return 'mp3'
  }
  return formats.includes(settings.responseFormat) ? settings.responseFormat : formats[0]!
}

function describeFormatParameter(formats: readonly TtsResponseFormat[], settings: TtsSettings): string {
  const parts = [`Audio format. Default: ${defaultFormat(formats, settings, undefined)} (from the settings).`]
  if (formats.includes('opus')) {
    parts.push('For Telegram replies use "opus" (OGG/Opus): it is shown as a native voice message and is the default there.')
  }
  return parts.join(' ')
}

function errorResult(text: string) {
  return { content: [{ type: 'text' as const, text }], details: { error: true } satisfies SendVoiceMessageToolDetails }
}

function deliveryNote(channel: string | undefined, extension: string): string {
  if (channel === 'telegram') {
    return isTelegramVoiceFormat(extension) ? 'as a Telegram voice message' : 'as a Telegram audio file'
  }
  return 'as an audio player in the chat'
}

/**
 * Create the `audio_send` tool: speaks `text` with the configured TTS
 * model and attaches the audio to the current turn. The `format` parameter is
 * only declared when the provider can return more than one format.
 */
export function createSendVoiceMessageTool(options: SendVoiceMessageToolOptions): AgentTool {
  const declaredSettings = options.settings ?? loadTtsSettings()
  const declaredFormats = getTtsModelResponseFormats(declaredSettings.model)

  const properties: Record<string, TSchema> = {
    text: Type.String({
      description: `What to say, written as natural speech in the language of the conversation (max ${MAX_SPEECH_CHARS} characters). `
        + 'No markdown, code, tables or URLs.',
    }),
  }
  if (declaredFormats.length > 1) {
    properties.format = Type.Optional(Type.Unsafe(StringEnum(declaredFormats, { description: describeFormatParameter(declaredFormats, declaredSettings) })))
  }

  return {
    name: SEND_VOICE_MESSAGE_TOOL_NAME,
    label: 'Send Voice Message',
    description:
      'Reply to the user with a spoken voice message generated by the configured text-to-speech model. '
      + 'Use it when the user asks for a voice or audio answer (e.g. "answer as a voice message"). '
      + 'The audio is delivered with this turn: on Telegram as a voice message, in the web chat as an audio player. '
      + 'Do not repeat the spoken content as text afterwards; a short confirmation or nothing is enough.',
    parameters: Type.Object(properties),
    execute: async (_toolCallId, params) => {
      const { text, format: requestedFormat } = params as { text: string; format?: TtsResponseFormat }

      try {
        const settings = loadTtsSettings()
        if (!isSendVoiceMessageToolEnabled(settings)) {
          return errorResult('Error: Voice messages are not enabled. Enable Text-to-Speech and "Provide as agent tool" in Settings → Text-to-Speech.')
        }

        const speech = stripMarkdownForSpeech(text ?? '')
        if (!speech) return errorResult('Error: text is empty.')
        if (speech.length > MAX_SPEECH_CHARS) {
          return errorResult(
            `Error: text is ${speech.length} characters (max ${MAX_SPEECH_CHARS}). Shorten it or split it into several voice messages.`,
          )
        }

        const channel = options.getChannel()
        const formats = getTtsModelResponseFormats(settings.model, speech.length)
        const format = requestedFormat && formats.includes(requestedFormat)
          ? requestedFormat
          : defaultFormat(formats, settings, channel)

        const userId = options.getCurrentUserId() ?? null
        const sessionId = options.getCurrentInteractiveSessionId() ?? null
        const audio = await synthesizeTts(speech, {
          settings: { responseFormat: format },
          ...(options.db && { usage: { db: options.db, sessionId, userId } }),
        })
        const uploaded: UploadDescriptor = {
          ...saveUpload({
            buffer: audio.audio,
            originalName: `voice-message.${audio.extension}`,
            mimeType: audio.contentType,
            source: channel === 'telegram' ? 'telegram' : 'web',
            userId,
            sessionId,
          }),
          voiceMessage: true,
        }

        return {
          content: [{
            type: 'text' as const,
            text: `Voice message prepared (${audio.extension}, ${speech.length} characters). It is delivered ${deliveryNote(channel, audio.extension)} with this turn. `
              + 'Do not repeat its content as text.',
          }],
          details: { uploadedFile: uploaded, format } satisfies SendVoiceMessageToolDetails,
        }
      } catch (err) {
        return errorResult(`Error creating voice message: ${err instanceof Error ? err.message : String(err)}`)
      }
    },
  }
}
